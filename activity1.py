# 1. Set your daily hours for each activity
sleep = 8
work = 8
exercise = 1
relaxing = 3

# 2. Multiply each activity by 7 to get weekly hours
weekly_sleep = sleep * 7
weekly_work = work * 7
weekly_exercise = exercise * 7
weekly_relaxing = relaxing * 7

# 3. Print the results
print("Sleep:", weekly_sleep, "hours a week")
print("Work:", weekly_work, "hours a week")
print("Exercise:", weekly_exercise, "hours a week")
print("Relaxing:", weekly_relaxing, "hours a week")
